"""Generate every copy of the gradient preset list from GradientPresets.json.

The overlay's named colour ramps are ONE list (Sources/AddOn/ArchViz/
GradientPresets.json). Four things repeat it and none is edited by hand:

- the C++ table `ArchViz/GradientLibraryTable.inc` that `PresetStops` reads;
- the Python list `evp/gradients.py`;
- every `"preset"` enum in the native overlay command schemas, which the
  dispatcher validates against and the v2 API catalog is generated from.

    python tools/generate_gradient_presets.py          # write
    python tools/generate_gradient_presets.py --check  # fail if any copy is stale

After a write, regenerate the API catalog with tools/generate_tapioca_api_v2.py.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

EVP = Path(__file__).resolve().parents[1]
ARCHVIZ = EVP / "Sources" / "AddOn" / "ArchViz"
SOURCE = ARCHVIZ / "GradientPresets.json"
TABLE = ARCHVIZ / "GradientLibraryTable.inc"
PYTHON = EVP / "Sources" / "PyPackage" / "evp" / "gradients.py"
SCHEMAS = [
    EVP / "Sources" / "AddOn" / "NativeCommands" / "OverlayCommands.cpp",
    EVP / "Sources" / "AddOn" / "NativeCommands" / "OverlayLayerCommands.cpp",
]
MAX_STOPS = 16  # layers::kMaxStops
PRESET_ENUM = re.compile(r'"preset":\{"type":"string","enum":\[[^\]]*\]\}')


def load() -> dict:
    document = json.loads(SOURCE.read_text(encoding="utf-8"))
    categories = document["categories"]
    seen = set()
    for preset in document["presets"]:
        ident = preset["id"]
        if ident == "custom":
            raise SystemExit("'custom' is reserved for the user's own stops (layers::kCustomGradientId)")
        if ident in seen:
            raise SystemExit(f"{ident}: duplicate id")
        seen.add(ident)
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", ident):
            raise SystemExit(f"{ident}: ids are lower-case words joined by '-'")
        if preset["category"] not in categories:
            raise SystemExit(f"{ident}: unknown category {preset['category']}")
        stops = preset["stops"]
        if not 2 <= len(stops) <= MAX_STOPS:
            raise SystemExit(f"{ident}: 2 to {MAX_STOPS} stops")
        positions = [at for at, _ in stops]
        if positions != sorted(positions) or positions[0] < 0 or positions[-1] > 1:
            raise SystemExit(f"{ident}: positions ascend inside 0..1")
        if not preset["min"] < preset["max"]:
            raise SystemExit(f"{ident}: min is below max")
    return document


def rgba(colour: str) -> int:
    value = colour.lstrip("#")
    if len(value) == 6:
        value += "FF"
    return int(value, 16)


def _float(value: float) -> str:
    text = repr(float(value))
    return text + "f" if "e" in text or "." in text else text + ".0f"


def _double(value: float) -> str:
    return repr(float(value))


def _camel(category: str) -> str:
    return category[:1].upper() + category[1:]


def render_table(document: dict) -> str:
    lines = [
        "// Generated by AddOn/EvP/tools/generate_gradient_presets.py from GradientPresets.json.",
        "// Do not edit; change the JSON and re-run the generator.",
        "// clang-format off",
    ]
    for preset in document["presets"]:
        stops = ", ".join(f"{{ {_float(at)}, 0x{rgba(colour):08X}u }}" for at, colour in preset["stops"])
        lines.append(
            f'{{ "{preset["id"]}", {json.dumps(preset["name"])}, GradientCategory::{_camel(preset["category"])}, '
            f'{"true" if preset["stepped"] else "false"}, {_double(preset["min"])}, {_double(preset["max"])}, '
            f'{len(preset["stops"])}, {{ {stops} }} }},'
        )
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def render_python(document: dict) -> str:
    rows = []
    for preset in document["presets"]:
        rows.append(
            f'    Gradient({preset["id"]!r}, {preset["name"]!r}, {preset["category"]!r}, '
            f'{preset["stepped"]!r}, {float(preset["min"])!r}, {float(preset["max"])!r}),'
        )
    return (
        '"""The overlay\'s named colour ramps, the ids `colormap=` accepts.\n\n'
        "Generated by AddOn/EvP/tools/generate_gradient_presets.py from GradientPresets.json;\n"
        "do not edit. `min`/`max` are each preset's suggested range, `stepped` whether it\n"
        "reads best as flat bands. A ramp's colours are the native add-on's.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "from typing import NamedTuple\n\n\n"
        "class Gradient(NamedTuple):\n"
        "    id: str\n"
        "    name: str\n"
        "    category: str\n"
        "    stepped: bool\n"
        "    min: float\n"
        "    max: float\n\n\n"
        f"CATEGORIES = {tuple(document['categories'])!r}\n\n"
        "GRADIENTS = (\n" + "\n".join(rows) + "\n)\n\n"
        "IDS = tuple(gradient.id for gradient in GRADIENTS)\n\n\n"
        "def get(gradient_id: str) -> Gradient:\n"
        '    """The preset called `gradient_id`; KeyError for a name the add-on does not know."""\n'
        "    for gradient in GRADIENTS:\n"
        "        if gradient.id == gradient_id:\n"
        "            return gradient\n"
        "    raise KeyError(gradient_id)\n"
    )


def _read(path: Path) -> str:
    # Untranslated: a checkout with autocrlf keeps its CRLF through a rewrite.
    with open(path, encoding="utf-8", newline="") as file:
        return file.read()


def render_schema(path: Path, document: dict) -> str:
    enum = ",".join(json.dumps(p["id"]) for p in document["presets"])
    replacement = f'"preset":{{"type":"string","enum":[{enum}]}}'
    text = _read(path)
    updated, count = PRESET_ENUM.subn(lambda _: replacement, text)
    if count == 0:
        raise SystemExit(f"{path.name}: no preset enum found")
    return updated


def outputs(document: dict) -> dict[Path, str]:
    result = {TABLE: render_table(document), PYTHON: render_python(document)}
    for path in SCHEMAS:
        result[path] = render_schema(path, document)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated copy is stale")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs(load()).items():
        current = _read(path) if path.exists() else ""
        if current.replace("\r\n", "\n") == text.replace("\r\n", "\n"):
            continue
        stale.append(path)
        if not args.check:
            with open(path, "w", encoding="utf-8", newline="") as file:
                file.write(text)
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'}: {path.relative_to(EVP)}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
