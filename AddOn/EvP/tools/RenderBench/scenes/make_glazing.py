"""Write glazing.obj / glazing.mtl: the bench's own glazing fixture (#231).

The archive scenes the suite uses have no architectural glass, so the traced style's glass was
never compared with the raster's. This is a room with a glazed front, a red back wall to be seen
through the pane, and a white block outside to be seen in it, on a ground plane under the sun.

Authored Z-up in metres and written Y-up, like the archive scenes, so run_suite passes --yup for
every case. Every solid is a closed box; the pane is a 20 mm box, as Archicad models a pane.

    python make_glazing.py        (writes beside this file)
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# name: Kd, d, Ns, Ks. The glass is what Archicad's classifier calls glass: transparency 70 %,
# specular 100, diffuse under 0.35 (SurfaceClassifier.hpp).
MATERIALS = {
    "ground": ((0.45, 0.45, 0.42), 1.0, 10.0, 0.0),
    "wall": ((0.80, 0.80, 0.78), 1.0, 10.0, 0.0),
    "backwall": ((0.60, 0.15, 0.10), 1.0, 10.0, 0.0),
    "block": ((0.85, 0.85, 0.85), 1.0, 10.0, 0.0),
    "glass": ((0.25, 0.30, 0.30), 0.3, 100.0, 1.0),
}

BOXES = [
    ("ground", (-20, -20, -0.1), (20, 20, 0)),
    ("wall", (-4, 5.8, 0), (4, 6, 3)),  # back wall, outside face
    ("backwall", (-3.8, 5.75, 0.05), (3.8, 5.8, 2.8)),  # its red inner lining
    ("wall", (-4, 0, 0), (-3.8, 6, 3)),  # left
    ("wall", (3.8, 0, 0), (4, 6, 3)),  # right
    ("wall", (-4, 0, 2.8), (4, 6, 3)),  # roof slab
    ("wall", (-3.8, 0.2, 0), (3.8, 5.8, 0.05)),  # floor slab
    ("wall", (-3.8, 0, 0), (3.8, 0.2, 0.6)),  # sill
    ("wall", (-3.8, 0, 2.4), (3.8, 0.2, 2.8)),  # header
    ("glass", (-3.8, 0.09, 0.6), (3.8, 0.11, 2.4)),  # the pane
    ("block", (-9, -6, 0), (-6, -3, 4)),  # outside, seen in the pane
]


def main():
    obj = ["# RenderBench glazing fixture, generated by make_glazing.py", "mtllib glazing.mtl"]
    count = 0
    for name, lo, hi in BOXES:
        obj.append(f"usemtl {name}")
        corners = [(x, y, z) for z in (lo[2], hi[2]) for y in (lo[1], hi[1]) for x in (lo[0], hi[0])]
        for x, y, z in corners:
            obj.append(f"v {x:g} {z:g} {-y:g}")  # Z-up -> Y-up
        # Corner k = x + 2y + 4z bits; each face counter-clockwise seen from outside (Z-up).
        faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        for f in faces:
            obj.append("f " + " ".join(str(count + k + 1) for k in f))
        count += 8
    mtl = []
    for name, (kd, d, ns, ks) in MATERIALS.items():
        mtl += [f"newmtl {name}", "Kd {:g} {:g} {:g}".format(*kd), f"d {d:g}", f"Ns {ns:g}",
                f"Ks {ks:g} {ks:g} {ks:g}", ""]
    (HERE / "glazing.obj").write_text("\n".join(obj) + "\n")
    (HERE / "glazing.mtl").write_text("\n".join(mtl))


if __name__ == "__main__":
    main()
