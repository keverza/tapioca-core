"""Write louvres.obj / louvres.mtl: the bench's louvre-facade fixture (#14).

A live check on a large project showed every raster style shimmering on a facade of thin vertical
slats -- moire on the surfaces, and in Technical the slats' outlines jumping the whole facade
between white and dark -- while the camera moved. The archive scenes have nothing that fine, so
this is that facade: a two-storey box behind a screen of 30 mm slats at 60 mm centres, a timber
screen of wider battens below it, on a ground plane under the sun.

Authored Z-up in metres and written Y-up, like the archive scenes, so run_suite passes --yup for
every case. Every solid is a closed box. Run with run_suite's `louvres` case and --extra
"--motion 48" to score the flicker while the camera moves.

    python make_louvres.py        (writes beside this file)
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# name: Kd, d, Ns, Ks
MATERIALS = {
    "ground": ((0.30, 0.38, 0.20), 1.0, 10.0, 0.0),
    "paving": ((0.62, 0.62, 0.60), 1.0, 10.0, 0.0),
    "wall": ((0.85, 0.85, 0.83), 1.0, 10.0, 0.0),
    "slat": ((0.90, 0.90, 0.90), 1.0, 30.0, 0.1),
    "timber": ((0.45, 0.30, 0.18), 1.0, 10.0, 0.0),
    "glass": ((0.25, 0.30, 0.30), 0.3, 100.0, 1.0),
}


def boxes():
    out = [
        ("ground", (-40, -40, -0.1), (40, 40, 0)),
        ("paving", (-12, -6, 0), (12, -1, 0.02)),
        ("wall", (-6, 0, 0), (6, 10, 0.3)),  # floor slab
        ("wall", (-6, 0, 3.3), (6, 10, 3.6)),  # first floor slab
        ("wall", (-6, 0, 6.6), (6, 10, 7.0)),  # roof slab
        ("wall", (-6, 9.7, 0), (6, 10, 7.0)),  # back wall
        ("wall", (-6, 0, 0), (-5.7, 10, 7.0)),  # left wall
        ("wall", (5.7, 0, 0), (6, 10, 7.0)),  # right wall
        ("glass", (-5.7, 1.0, 0.3), (5.7, 1.02, 6.6)),  # glazing behind the screens
        ("wall", (-6, -0.6, 3.3), (6, 0.0, 3.6)),  # screen frame, bottom
        ("wall", (-6, -0.6, 6.6), (6, 0.0, 7.0)),  # screen frame, top
    ]
    # Upper screen: 30 mm slats at 60 mm centres, 150 mm deep, 3 m tall.
    x = -5.9
    while x < 5.9:
        out.append(("slat", (x, -0.45, 3.6), (x + 0.03, -0.30, 6.6)))
        x += 0.06
    # Lower screen: 40 mm battens at 100 mm centres.
    x = -5.9
    while x < 5.9:
        if not (-1.0 < x < 1.0):  # the entrance
            out.append(("timber", (x, -0.45, 0.3), (x + 0.04, -0.35, 3.3)))
        x += 0.10
    return out


def main():
    obj = ["# RenderBench louvre fixture, generated by make_louvres.py", "mtllib louvres.mtl"]
    count = 0
    for name, lo, hi in boxes():
        obj.append(f"usemtl {name}")
        corners = [(x, y, z) for z in (lo[2], hi[2]) for y in (lo[1], hi[1]) for x in (lo[0], hi[0])]
        for x, y, z in corners:
            obj.append(f"v {x:.4f} {z:.4f} {-y:.4f}")  # Z-up -> Y-up
        # Corner k = x + 2y + 4z bits; each face counter-clockwise seen from outside (Z-up).
        faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        for f in faces:
            obj.append("f " + " ".join(str(count + k + 1) for k in f))
        count += 8
    mtl = []
    for name, (kd, d, ns, ks) in MATERIALS.items():
        mtl += [
            f"newmtl {name}",
            "Kd {:g} {:g} {:g}".format(*kd),
            f"d {d:g}",
            f"Ns {ns:g}",
            f"Ks {ks:g} {ks:g} {ks:g}",
            "",
        ]
    (HERE / "louvres.obj").write_text("\n".join(obj) + "\n")
    (HERE / "louvres.mtl").write_text("\n".join(mtl))


if __name__ == "__main__":
    main()
