"""Write joints.obj / joints.mtl: the bench's coplanar-joint fixture (#14).

Technical drew a line wherever one element's face ran on, flush, into another's: wall segments, a
slab edge level with the wall face, the next wall around a corner (live check: "the inside edges
should not be visible, like in ray traced the wall is clean"). This is that wall: three segments
flush along one face under a slab flush with it, a return wall at the corner, and a panel standing
2 cm proud of the face, whose outline is a real step and must stay.

The bench makes one element per material, so every box has its own material (in the same colour):
each joint is between two elements, as in Archicad. Authored Z-up in metres and written Y-up, like
the archive scenes, so run_suite passes --yup.

    python make_joints.py        (writes beside this file)
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

WALL = (0.80, 0.80, 0.78)


def boxes():
    return [
        ("ground", (0.30, 0.38, 0.20), (-30, -30, -0.1), (30, 30, 0)),
        ("wall_a", WALL, (-6, 0, 0), (-2, 0.3, 3)),  # three segments, flush along y = 0
        ("wall_b", WALL, (-2, 0, 0), (2, 0.3, 3)),
        ("wall_c", WALL, (2, 0, 0), (6, 0.3, 3)),
        ("slab", WALL, (-6, 0, 3), (6, 5, 3.3)),  # flush with the wall face and its ends
        ("return", WALL, (5.7, 0.3, 0), (6, 5, 3)),  # flush with wall_c's end face x = 6
        ("panel", WALL, (-1, -0.02, 0.5), (1, 0, 2.5)),  # 2 cm proud: a real step
    ]


def main():
    obj = ["# RenderBench coplanar-joint fixture, generated by make_joints.py", "mtllib joints.mtl"]
    mtl = []
    count = 0
    for name, kd, lo, hi in boxes():
        mtl += [f"newmtl {name}", "Kd {:g} {:g} {:g}".format(*kd), "d 1", "Ns 10", "Ks 0 0 0", ""]
        obj.append(f"usemtl {name}")
        corners = [(x, y, z) for z in (lo[2], hi[2]) for y in (lo[1], hi[1]) for x in (lo[0], hi[0])]
        for x, y, z in corners:
            obj.append(f"v {x:.4f} {z:.4f} {-y:.4f}")  # Z-up -> Y-up
        # Corner k = x + 2y + 4z bits; each face counter-clockwise seen from outside (Z-up).
        faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        for f in faces:
            obj.append("f " + " ".join(str(count + k + 1) for k in f))
        count += 8
    (HERE / "joints.obj").write_text("\n".join(obj) + "\n")
    (HERE / "joints.mtl").write_text("\n".join(mtl))


if __name__ == "__main__":
    main()
