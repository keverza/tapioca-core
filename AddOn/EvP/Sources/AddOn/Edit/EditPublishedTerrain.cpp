bool PublishUnifiedTerrain (const UnifiedTerrainResult& unified, const FieldPlan& plan, const TerrainCapture& baseline,
                            const UnifiedLandscapeBuildScope& scope, PublishedTerrain& published, std::string& error)
{
    error.clear ();
    try {
        PublishedTerrain candidate;
        candidate.points = unified.points;
        candidate.base = unified.base;
        candidate.triangles = unified.triangles;
        candidate.owners = unified.owners;
        candidate.mappings = unified.mappings;
        candidate.lines = unified.lines;
        candidate.ownersIdentity = StackIdentity (plan, error);
        if (!error.empty ())
            return false;
        candidate.inputProvenance = unified.inputProvenance;
        if (!ProjectMeshProvenance (unified, candidate.meshProvenance, error))
            return false;
        candidate.rebuildRegion = scope.rebuildRegion;
        candidate.measurementRegion = scope.measurementRegion;
        for (const auto& locked : unified.locked) {
            if (locked.control >= plan.controls.size ()) {
                error = "PublishedTerrainAttribution: a locked vertex names no plan control";
                return false;
            }
            const auto& control = plan.controls[locked.control];
            candidate.locked.push_back (
                { locked.vertex, locked.height, uint64_t (control.source), uint64_t (control.vertex), control.point });
        }
        std::vector<DomainFootprint> footprints;
        for (const auto& entry : plan.entries) {
            DomainFootprint footprint { entry.order, entry.rootOperation, entry.object, {} };
            for (const auto& part : entry.parts) {
                footprint.parts.push_back ({});
                for (const auto& ring : part.rings)
                    footprint.parts.back ().push_back (Flat (ring));
            }
            footprints.push_back (std::move (footprint));
        }
        QuantityRows quantities;
        if (!ComputeQuantities (candidate.points, candidate.base, candidate.triangles, candidate.owners,
                                candidate.ownersIdentity, &footprints, quantities, error))
            return false;
        candidate.quantities = quantities.total;
        candidate.domainQuantities = std::move (quantities.rows);
        // Kernel-exact site/context are measured against the rebuild region;
        // retained alongside, never silently replacing the displayed totals.
        candidate.exactSite = unified.site;
        candidate.exactContext = unified.context;
        if (!MeasureDisplayTotals (baseline, candidate.measurementRegion, candidate, error))
            return false;
        candidate.revision = unified.revision;
        candidate.planHash = unified.planHash;
        candidate.session = plan.session;
        candidate.sourceTerrainGuid = plan.sourceTerrainGuid;
        published = std::move (candidate);
        error.clear ();
        return true;
    }
    catch (const std::exception& exception) {
        error = std::string ("PublishUnifiedTerrain: ") + exception.what ();
        return false;
    }
}

bool PublishTerrainDesign (const TerrainDesignOutcome& outcome, OperationId operation, ObjectId object,
                           std::span<const double> measurementRegion, PublishedTerrain& published, std::string& error)
{
    error.clear ();
    try {
        if (!outcome.built) {
            error = "PublishTerrainDesign: a refused outcome has no terrain to publish";
            return false;
        }
        const auto& design = outcome.result;
        const auto& build = design.build;
        PublishedTerrain candidate;
        candidate.points = build.points;
        candidate.base = build.base;
        candidate.triangles = build.triangles;
        candidate.owners = build.owners;
        candidate.mappings = build.mappings;
        candidate.ownersIdentity = { { 0, operation, object, true } };
        for (const auto& line : build.lines)
            candidate.lines.push_back ({ UnifiedLineDomain::Path, 0, 0, 0, 0, line.kind, line.side, line.root });
        for (const auto& locked : design.locked) {
            PublishedLocked row { locked.vertex, 0, 0, 0, true };
            if (locked.vertex * 3 + 2 < build.points.size ())
                row.height = build.points[locked.vertex * 3 + 2];
            if (!locked.supports.empty ()) {
                row.source = uint64_t (locked.supports.front ().source);
                row.authoredVertex = uint64_t (locked.supports.front ().vertices[0]);
            }
            candidate.locked.push_back (row);
        }
        candidate.inputProvenance = build.inputProvenance;
        candidate.meshProvenance = design.meshProvenance;
        candidate.rebuildRegion = design.region;
        candidate.measurementRegion.assign (measurementRegion.begin (), measurementRegion.end ());
        QuantityRows quantities;
        if (!ComputeQuantities (candidate.points, candidate.base, candidate.triangles, candidate.owners,
                                candidate.ownersIdentity, nullptr, quantities, error))
            return false;
        candidate.quantities = quantities.total;
        candidate.domainQuantities = std::move (quantities.rows);
        // The legacy lane's totals already carry the 0.25 m convention from the
        // landscape job; it does not separate exact volumes.
        candidate.displaySite = build.site;
        candidate.displayContext = build.context;
        if (outcome.capture && !MeasureDisplayTotals (*outcome.capture, candidate.measurementRegion, candidate, error))
            return false;
        candidate.revision = design.revision;
        candidate.session = outcome.session;
        candidate.sourceTerrainGuid = outcome.sourceTerrainGuid;
        published = std::move (candidate);
        error.clear ();
        return true;
    }
    catch (const std::exception& exception) {
        error = std::string ("PublishTerrainDesign: ") + exception.what ();
        return false;
    }
}

