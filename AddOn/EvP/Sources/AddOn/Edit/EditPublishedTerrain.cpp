std::vector<double> Flat (const std::vector<edit::Vec3>& points)
{
    std::vector<double> flat;
    flat.reserve (points.size () * 3);
    for (const auto& point : points)
        flat.insert (flat.end (), { point.x, point.y, point.z });
    return flat;
}

// ---- domains=7 -> domains=5 projection --------------------------------------
// Every output entity is attributed. The baseline mesh prefix keeps its exact
// ancestry: output vertices below the mesh input count are those input
// vertices unchanged (the rebuild retains them verbatim), re-emitted through
// the input table, which is pushed as the single support table -- the native
// baseline prefix is thereby preserved verbatim. Rebuild-created vertices
// (ring insertions, crossings, control spots) are generated by the build,
// citing every catalog contributor; per-vertex ring ancestry refinement waits
// for the kernel to document its breakline-ordinal catalog mapping. Faces
// resolve through their kind-12 correspondence rows: verbatim triangles keep
// their parent face row; re-triangulated faces are fragments of their parent
// input face.
bool ProjectMeshProvenance (const UnifiedTerrainResult& unified, ProvenanceRequest& output, std::string& error)
{
    const auto& input = unified.inputProvenance;
    if (unified.inputPointCount > unified.points.size () / 3) {
        error = "PublishedTerrainShape: the mesh prefix exceeds the output vertex count";
        return false;
    }
    terrain_detail::InputRows rows (input);
    std::vector<const TerrainMapping*> faceRows (unified.triangles.size () / 3, nullptr);
    for (const auto& mapping : unified.mappings)
        if (mapping.kind == TerrainMappingKind::RegionFace) {
            if (mapping.index >= faceRows.size () || faceRows[mapping.index]) {
                error = "PublishedTerrainAttribution: a region face maps no unique correspondence row";
                return false;
            }
            faceRows[mapping.index] = &mapping;
        }
    for (const auto* row : faceRows)
        if (!row) {
            error = "PublishedTerrainAttribution: an output face has no region correspondence row";
            return false;
        }

    std::set<SourceId> contributors;
    std::set<OperationId> catalogOperations;
    for (const auto& row : input.table.mappings) {
        for (uint64_t i = 0; i < row.sources.count; ++i)
            contributors.insert (input.table.sourceIds.at (row.sources.offset + i));
        for (uint64_t i = 0; i < row.operations.count; ++i)
            catalogOperations.insert (input.table.operationIds.at (row.operations.offset + i));
    }
    contributors.erase (0);
    catalogOperations.erase (0);
    const ObjectId owner = rows.vertices.empty () ? 0 : rows.vertices.front ()->object;

    output = input;
    std::set<uint64_t> used { input.table.context.tableId };
    for (const auto& support : input.table.supportTables)
        used.insert (support.context.tableId);
    uint64_t token = 1;
    while (used.count (token))
        ++token;
    output.table.context.tableId = token;
    output.domains = kMeshProvenanceDomains;
    output.counts = { uint64_t (unified.points.size () / 3), 0, uint64_t (unified.triangles.size () / 3), 0 };
    output.table.supportTables.push_back ({ input.table.context, input.counts, false });
    output.table.mappings.clear ();
    for (uint64_t vertex = 0; vertex < output.counts.vertices; ++vertex) {
        if (vertex < unified.inputPointCount) {
            const auto* parent = rows.vertices.at (vertex);
            output.table.mappings.push_back (
                Supported (*parent, IdentityDomain::Vertex, vertex, input.table.context.tableId, output.table));
            continue;
        }
        EntityMapping row;
        row.domain = IdentityDomain::Vertex;
        row.kind = MappingKind::Generated;
        row.outputIndex = vertex;
        row.object = owner;
        row.sources = terrain_detail::Append (output.table.sourceIds, contributors);
        row.operations = terrain_detail::Append (output.table.operationIds, catalogOperations);
        output.table.mappings.push_back (row);
    }
    for (uint64_t face = 0; face < output.counts.faces; ++face) {
        const TerrainMapping& mapping = *faceRows.at (face);
        const auto* parent = rows.faces.at (mapping.values[0]);
        if (mapping.values[2] == 1) {
            output.table.mappings.push_back (
                Supported (*parent, IdentityDomain::Face, face, input.table.context.tableId, output.table));
            continue;
        }
        const EntityPredecessor predecessor { input.table.context.tableId, IdentityDomain::Face, mapping.values[0] };
        const std::array<const EntityMapping*, 1> parents { parent };
        output.table.mappings.push_back (terrain_detail::Fragment (
            input, parents, IdentityDomain::Face, face, input.table.operationIds.at (parent->operations.offset),
            input.table.sourceIds.at (parent->sources.offset),
            std::span<const EntityPredecessor> { std::array<EntityPredecessor, 1> { predecessor } }, output));
    }
    return terrain_detail::Validate (output, error);
}

// ---- domain footprints -------------------------------------------------------
// One entry footprint: per evaluated domain part, rings[0] is the outer and
// rings[1..] its holes — the plan's own PolyTree nesting. Parts are kept
// separate: flattening every part into one pseudo-polygon would treat a second
// outer as a hole of the first and lose its island attribution.
struct DomainFootprint {
    uint32_t order = 0;
    OperationId operation = 0;
    ObjectId object = 0;
    std::vector<std::vector<std::vector<double>>> parts; // Per part: flat xyz rings.
};

bool InsideRing (const std::vector<double>& ring, double x, double y)
{
    bool inside = false;
    const size_t count = ring.size () / 3;
    for (size_t a = 0; a < count; ++a) {
        const size_t b = (a + 1) % count;
        const double ay = ring[a * 3 + 1], by = ring[b * 3 + 1];
        if ((ay > y) != (by > y)) {
            const double cross = ring[b * 3] - ring[a * 3];
            if (x < ring[a * 3] + (y - ay) / (by - ay) * cross)
                inside = !inside;
        }
    }
    return inside;
}

bool InsideFootprint (const DomainFootprint& domain, double x, double y)
{
    for (const auto& rings : domain.parts) {
        if (rings.empty () || !InsideRing (rings.front (), x, y))
            continue;
        bool hole = false;
        for (size_t ring = 1; ring < rings.size () && !hole; ++ring)
            hole = InsideRing (rings[ring], x, y);
        if (!hole)
            return true;
    }
    return false;
}

// ---- exact triangle integration with zero-contour cut/fill split -------------
struct ClipVertex {
    std::array<double, 3> xy; // z slot carries the affine height difference.
};

// Sutherland-Hodgman against the half-plane keepPositive ? d >= 0 : d <= 0.
// Intersection points carry d == 0, so the fan integral below stays exact.
std::vector<ClipVertex> ClipDifference (const std::array<ClipVertex, 3>& triangle, bool keepPositive)
{
    auto inside = [keepPositive] (const ClipVertex& vertex) {
        return keepPositive ? vertex.xy[2] >= 0.0 : vertex.xy[2] <= 0.0;
    };
    std::vector<ClipVertex> output;
    for (size_t index = 0; index < 3; ++index) {
        const ClipVertex& current = triangle[index];
        const ClipVertex& previous = triangle[(index + 2) % 3];
        const bool currentIn = inside (current), previousIn = inside (previous);
        if (currentIn != previousIn) {
            const double span = previous.xy[2] - current.xy[2];
            const double t = span != 0.0 ? previous.xy[2] / span : 0.0;
            ClipVertex crossing {};
            for (size_t axis = 0; axis < 2; ++axis)
                crossing.xy[axis] = previous.xy[axis] + t * (current.xy[axis] - previous.xy[axis]);
            output.push_back (crossing);
        }
        if (currentIn)
            output.push_back (current);
    }
    return output;
}

// Signed exact integral of the affine height difference over a convex clipped
// polygon: fan triangulation, V = A * (d0 + d1 + d2) / 3 per fan triangle.
double IntegratePiece (const std::vector<ClipVertex>& polygon)
{
    double integral = 0.0;
    for (size_t index = 1; index + 1 < polygon.size (); ++index) {
        const auto &a = polygon[0].xy, b = polygon[index].xy, c = polygon[index + 1].xy;
        const double twiceArea = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
        integral += twiceArea * (a[2] + b[2] + c[2]) / 6.0;
    }
    return integral;
}

// ---- quantities ---------------------------------------------------------------
struct QuantityRows {
    HybridVolumes total;
    std::vector<PublishedDomainQuantity> rows;
};

uint32_t RowFor (QuantityRows& quantities, uint32_t order, const PublishedOwner* identity)
{
    for (size_t index = 0; index < quantities.rows.size (); ++index)
        if (quantities.rows[index].order == order)
            return uint32_t (index);
    PublishedDomainQuantity row;
    row.order = order;
    if (identity) {
        row.operation = identity->operation;
        row.object = identity->object;
    }
    quantities.rows.push_back (row);
    return uint32_t (quantities.rows.size () - 1);
}

// Authoritative earthwork quantities: per output triangle the height difference
// to the sampled baseline is affine, so each triangle is clipped at its
// zero-difference contour and both pieces integrate exactly; cut and fill are
// therefore separated at the contour, not by triangle granularity. Attribution
// is geometric first — a domain claims the triangles inside its footprint
// (holes excluded, later stack positions override within their footprint;
// every domain ring is a constrained breakline of this very triangulation, so
// no triangle straddles a boundary and the centroid test is exact) — and falls
// back to the highest ordered vertex owner outside footprints (transition
// bands), else the triangle reconciles into the UINT32_MAX baseline row. A
// triangle is attributed whole; the zero-contour split only separates signs.
bool ComputeQuantities (const std::vector<double>& points, const std::vector<double>& base,
                        const std::vector<uint32_t>& triangles, const std::vector<std::optional<uint32_t>>& owners,
                        const std::vector<PublishedOwner>& identity, const std::vector<DomainFootprint>* footprints,
                        QuantityRows& quantities, std::string& error)
{
    const size_t vertexCount = points.size () / 3;
    if (base.size () != vertexCount || owners.size () != vertexCount || triangles.size () % 3 != 0) {
        error = "PublishedTerrainShape: baseline heights, owners and triangles do not describe the mesh";
        return false;
    }
    quantities = QuantityRows {};
    constexpr uint32_t kBaseline = UINT32_MAX;
    RowFor (quantities, kBaseline, nullptr);
    // One row per stack slot up front, in stack order: a domain that moved no
    // triangle still reports an explicit zero row instead of vanishing from
    // the partition.
    for (const auto& owner : identity)
        RowFor (quantities, owner.order, &owner);
    for (size_t corner = 0; corner < vertexCount; ++corner)
        if (owners[corner] && *owners[corner] >= identity.size ()) {
            error = "PublishedTerrainAttribution: an owner value names no stack identity";
            return false;
        }
    for (size_t face = 0; face < triangles.size (); face += 3) {
        std::array<ClipVertex, 3> triangle {};
        std::array<const uint32_t*, 3> ownerValues {};
        for (size_t corner = 0; corner < 3; ++corner) {
            const uint32_t vertex = triangles[face + corner];
            if (size_t (vertex) >= vertexCount) {
                error = "PublishedTerrainShape: a triangle index is out of range";
                return false;
            }
            triangle[corner].xy = { points[size_t (vertex) * 3], points[size_t (vertex) * 3 + 1],
                                    points[size_t (vertex) * 3 + 2] - base[vertex] };
            ownerValues[corner] = owners[vertex] ? &*owners[vertex] : nullptr;
        }
        // Geometric claim: the claiming domain with the highest stack order.
        const double cx = (triangle[0].xy[0] + triangle[1].xy[0] + triangle[2].xy[0]) / 3.0;
        const double cy = (triangle[0].xy[1] + triangle[1].xy[1] + triangle[2].xy[1]) / 3.0;
        uint32_t attributed = kBaseline;
        if (footprints) {
            bool claimed = false;
            for (const auto& domain : *footprints)
                if ((!claimed || domain.order > attributed) && InsideFootprint (domain, cx, cy)) {
                    attributed = domain.order;
                    claimed = true;
                }
        }
        if (attributed == kBaseline) {
            const uint32_t* best = nullptr;
            for (const uint32_t* owner : ownerValues)
                if (owner && (!best || *owner > *best))
                    best = owner;
            if (best)
                attributed = *best;
        }
        PublishedDomainQuantity& row =
            quantities.rows[RowFor (quantities, attributed, attributed == kBaseline ? nullptr : &identity[attributed])];
        const auto positive = ClipDifference (triangle, true);
        const auto negative = ClipDifference (triangle, false);
        const double fill = std::fabs (IntegratePiece (positive));
        const double cut = std::fabs (IntegratePiece (negative));
        const double area2 =
            std::fabs ((triangle[1].xy[0] - triangle[0].xy[0]) * (triangle[2].xy[1] - triangle[0].xy[1]) -
                       (triangle[1].xy[1] - triangle[0].xy[1]) * (triangle[2].xy[0] - triangle[0].xy[0]));
        row.fill += fill;
        row.cut += cut;
        row.net += fill - cut;
        row.area += area2 / 2.0;
        row.triangles += 1;
        quantities.total.fill += fill;
        quantities.total.cut += cut;
        quantities.total.net += fill - cut;
        quantities.total.area += area2 / 2.0;
        quantities.total.triangles += 1;
    }
    return true;
}

HybridVolumes ToVolumes (const TerrainVolumes& volumes)
{
    return HybridVolumes { volumes.cut, volumes.fill, volumes.net, volumes.area, 0 };
}

// Display totals: the existing 0.25 m measured-grid convention against the
// measurement region. A visualization/validation tool, never the authority.
bool MeasureDisplayTotals (const TerrainCapture& baseline, std::span<const double> measurementRegion,
                           PublishedTerrain& published, std::string& error)
{
    TerrainVolumeRequest request;
    request.existing = { baseline.points, baseline.triangles };
    request.proposed = TerrainVolumeRequest::Proposed::Mesh;
    request.proposedMesh = { published.points, published.triangles };
    request.cell = 0.25;
    request.property = measurementRegion;
    TerrainVolumeReport report;
    if (!MeasureTerrainVolumes (request, report, error))
        return false;
    published.displaySite = ToVolumes (report.site);
    published.displayContext = ToVolumes (report.context);
    return true;
}

std::vector<PublishedOwner> StackIdentity (const FieldPlan& plan, std::string& error)
{
    std::vector<PublishedOwner> identity;
    identity.reserve (plan.entries.size () + plan.paths.size () + plan.outlines.size ());
    for (const auto& entry : plan.entries)
        identity.push_back ({ entry.order, entry.rootOperation, entry.object, false });
    for (const auto& outline : plan.outlines)
        identity.push_back ({ outline.order, outline.operation, outline.object, true });
    for (const auto& path : plan.paths)
        identity.push_back ({ path.order, path.operation, path.object, true });
    std::sort (identity.begin (), identity.end (),
               [] (const PublishedOwner& a, const PublishedOwner& b) { return a.order < b.order; });
    for (size_t index = 0; index < identity.size (); ++index)
        if (identity[index].order != index) {
            error = "PublishedTerrainAttribution: the compiled plan stack is not contiguous";
            return {};
        }
    return identity;
}

