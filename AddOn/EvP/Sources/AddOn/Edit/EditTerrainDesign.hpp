#ifndef TAPIOCA_EDIT_TERRAIN_DESIGN_HPP
#define TAPIOCA_EDIT_TERRAIN_DESIGN_HPP

#include "Edit/EditLandscape.hpp"
#include "Edit/EditTerrainAdapter.hpp"
#include "Geometry/GeometryRustHybridTerrain.hpp"

namespace tapioca::geometry {

struct TerrainDesignOptions {
    OperationId operation = 0; // Enabled DAG operation that consumes `source`.
    ObjectId object = 0;       // One existing terrain owner; mixed ownership refuses.
    Id source = kNoId;         // PathCenterline source naming the document path.
    // Closed straight xyz ring bounding the rebuild (z ignored). P1 takes it from
    // the caller; deriving it from the band's reach is the composition phase's.
    std::span<const double> region;
    double maxStep = 2.0;                 // Station spacing, metres (plus every break).
    double cutLimit = 10, fillLimit = 10; // Plan reach of each face, metres.
    TerrainEditEffect effect = TerrainEditEffect::Both;
    double tolerance = 1e-3; // At-grade height band, metres.
    // Caller-owned transient table tokens, NOT authored IDs: new within the
    // input's retained support set and distinct from each other.
    uint64_t designTable = 0, meshTable = 0;
};
struct TerrainDesignResult {
    uint64_t revision = 0;
    std::string sourceTerrainGuid;
    std::vector<double> stations; // Path stations the band was sampled at.
    HybridTerrainResult build;    // Rust result; inputProvenance is the design input (domains=7).
    // Vertex/face attribution of the rebuilt base mesh (domains=5): input
    // vertices and verbatim faces exact, split and crossing vertices and
    // re-triangulated faces fragments of their real parents, pure design-line
    // vertices generated by the path. Heights are attributed separately.
    ProvenanceRequest meshProvenance;
    std::vector<std::optional<OperationId>> vertexOperations; // Band-moved heights.
    bool operator== (const TerrainDesignResult&) const = default;
};

// Worker-only P1 band evaluation for one document path. Stations come from the
// path itself (SampleStations, Evaluate: profile height, range widths, shoulder,
// crossfall or crown and cut/fill percents as Slope::Percent); nothing is
// re-solved here and no terrain math is implemented in C++. A crowned range makes
// the centreline a breakline (the crown's crease). Publishes the whole result once,
// after checking that every outside-region vertex kept its base height bits.
// No history, persistence or native write; the host rechecks revision/session.
bool EvaluateTerrainDesign (const geomsrv::edit::Document& doc, const EditTerrainInput& input,
                            const TerrainDesignOptions& options, TerrainDesignResult& result, std::string& error);

} // namespace tapioca::geometry
#endif
