#ifndef TAPIOCA_EDIT_TERRAIN_DESIGN_HPP
#define TAPIOCA_EDIT_TERRAIN_DESIGN_HPP

#include "Edit/EditLandscape.hpp"
#include "Edit/EditTerrainAdapter.hpp"
#include "Geometry/GeometryRustHybridTerrain.hpp"

namespace tapioca::geometry {

struct TerrainDesignOptions {
    OperationId operation = 0; // Enabled DAG operation that consumes `source`.
    ObjectId object = 0;       // One existing terrain owner; mixed ownership refuses.
    Id source = kNoId;         // PathCenterline source naming the document path.
    // Closed straight xyz ring bounding the rebuild (z ignored). Empty derives it
    // from the band's reach: the stations offset by the widest half width,
    // shoulder and face limit plus `margin` (round joins and ends, chords within
    // `arcTolerance`), clipped to the property line; exactly one ring must remain.
    std::span<const double> region;
    double margin = 1.0, arcTolerance = 0.05; // Metres.
    double maxStep = 2.0;                     // Station spacing, metres (plus every break).
    // A cross-section range change (width, crossfall, shoulder, slopes) runs over
    // this many metres ending at the range start. A zero-length step would make
    // the band discontinuous; its end faces need corner fans (composition phase).
    double taper = 0.5;
    double cutLimit = 10, fillLimit = 10; // Plan reach of each face, metres.
    TerrainEditEffect effect = TerrainEditEffect::Both;
    double tolerance = 1e-3; // At-grade height band, metres.
    // Caller-owned transient table tokens, NOT authored IDs: new within the
    // input's retained support set and distinct from each other.
    uint64_t designTable = 0, meshTable = 0;
};
// An authored control reference, resolved from explicit kernel input locators.
// Segment controls retain both endpoint IDs; points use vertices[0] only.
struct TerrainDesignControlRef {
    Id source = kNoId, segment = kNoId;
    std::array<Id, 2> vertices {};
    bool operator== (const TerrainDesignControlRef&) const = default;
};
// A located conflict in the path's own terms, or on an authored fixed control.
struct TerrainDesignConflict {
    HybridConflictCode code = HybridConflictCode::DaylightNotReached;
    double station = 0; // Path station, metres from its start.
    TerrainHand side = TerrainHand::Left;
    std::array<double, 3> position {}; // World metres: the band edge or where a face search stopped.
    double magnitude = 0;              // Per code (GeometryRustHybridTerrain.hpp).
    bool hard = true;                  // The build refuses on it.
    std::optional<TerrainDesignControlRef> control, other; // LockedConflict has no station/side semantics.
    bool operator== (const TerrainDesignConflict&) const = default;
};
struct TerrainDesignResult {
    uint64_t revision = 0;
    std::string sourceTerrainGuid;
    std::vector<double> stations; // Path stations the band was sampled at.
    std::vector<double> region;   // The ring actually rebuilt (caller's or derived), xyz.
    HybridTerrainResult build;    // Rust result; inputProvenance is the design input (domains=7).
    // Vertex/face attribution of the rebuilt base mesh (domains=5): input
    // vertices and verbatim faces exact, split and crossing vertices and
    // re-triangulated faces fragments of their real parents, pure design-line
    // vertices generated by the path. Heights are attributed separately.
    ProvenanceRequest meshProvenance;
    std::vector<std::optional<OperationId>> vertexOperations; // Band-moved heights.
    std::vector<TerrainDesignConflict> conflicts;             // Soft: where the band is held back.
    struct FixedVertex {
        uint32_t vertex = 0;
        std::vector<TerrainDesignControlRef> supports;
        bool operator== (const FixedVertex&) const = default;
    };
    std::vector<FixedVertex> locked; // Exact height is build.points[vertex*3+2].
    bool operator== (const TerrainDesignResult&) const = default;
};

// Worker-only band evaluation for one document path and the session's enabled
// fixed point/line references. Stations come from the
// path itself (SampleStations, Evaluate: profile height, range widths, shoulder,
// crossfall or crown and cut/fill percents as Slope::Percent); nothing is
// re-solved here and no terrain math is implemented in C++. A crowned range makes
// the centreline a breakline (the crown's crease). Each station carries the
// range in force there; a range change is a short explicit taper (`taper`)
// rather than a ramp across the whole sample spacing. Publishes the whole result once,
// after checking that every outside-region vertex kept its base height bits.
// No history, persistence or native write; the host rechecks revision/session.
// A refusal caused by a hard conflict names its first place in the message
// ("... at station 12.50 m, left, x y; N located"); AssessTerrainDesign lists all.
bool EvaluateTerrainDesign (const geomsrv::edit::Document& doc, const EditTerrainInput& input,
                            const TerrainDesignOptions& options, TerrainDesignResult& result, std::string& error);

// Every station-side and canonical fixed-control conflict, using the
// same authored references/validation as evaluation. Controls require a TIN
// build; hard band rows prevent fixed assessment. Nothing publishes but
// `conflicts`, unchanged on non-located refusal.
bool AssessTerrainDesign (const geomsrv::edit::Document& doc, const EditTerrainInput& input,
                          const TerrainDesignOptions& options, std::vector<TerrainDesignConflict>& conflicts,
                          std::string& error);

} // namespace tapioca::geometry
#endif
